import os
import torch
import pandas as pd
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms

class ImageExpertDataset(Dataset):
    def __init__(self, csv_file, transform=None):
        """
        Loads the mmotu_train.csv or mmotu_val.csv file.
        """
        self.df = pd.read_csv(csv_file)
        self.transform = transform or transforms.Compose([
            transforms.Resize((224, 224)),
            transforms.RandomHorizontalFlip(p=0.5),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
        ])

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        img_path = str(row['image_path'])
        
        if os.path.exists(img_path):
            image = Image.open(img_path).convert('RGB')
        else:
            # Fallback if image is missing
            image = Image.new('RGB', (224, 224), color=0)
            
        image = self.transform(image)
        # Parse the binary label (0 or 1) generated by preprocessing
        label = torch.tensor(int(row['label']), dtype=torch.long)
        return image, label

class TabularExpertDataset(Dataset):
    def __init__(self, csv_file):
        self.data = pd.read_csv(csv_file)
        # Assuming the target column is named 'RiskTier'
        self.labels = self.data['RiskTier'].values
        self.features = self.data.drop(columns=['RiskTier']).values

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        features = torch.tensor(self.features[idx], dtype=torch.float32)
        label = torch.tensor(self.labels[idx], dtype=torch.long)
        return features, label